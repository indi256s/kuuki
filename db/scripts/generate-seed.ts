/**
 * generate-seed.ts — Phase 5 reference-seed SQL generator.
 *
 * Emits committable, idempotent seed SQL for the four reference tables:
 *   - aircraft_reference   (from @kuuki/data aircraft.json, dedup on icao)
 *   - airports_reference   (from @kuuki/data airports.json)
 *   - badge_definitions    (from db/_snapshot/badge_definitions.json)
 *   - _code_adjectives     (from db/_snapshot/code_adjectives.json)
 *   - _code_nouns          (from db/_snapshot/code_nouns.json)
 *
 * Column lists match db/migrations/0001_init.sql EXACTLY. Reads files only —
 * never touches D1. Run: npx tsx db/scripts/generate-seed.ts
 *
 * Idempotency: each file is DELETE-preamble + INSERT (full reload of the
 * reference table) so re-applying is safe and deterministic.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO = join(__dirname, '..', '..') // db/scripts -> repo root
const DATA = join(REPO, 'packages', 'data', 'src')
const SNAP = join(REPO, 'db', '_snapshot')
const OUT = join(REPO, 'db', 'seed')

// ---------------------------------------------------------------------------
// SQL value helpers
// ---------------------------------------------------------------------------
function sqlStr(v: string): string {
  return `'${v.replace(/'/g, "''")}'`
}
/** string | null -> quoted-escaped | NULL */
function sqlNullableStr(v: string | null | undefined): string {
  return v === null || v === undefined ? 'NULL' : sqlStr(v)
}
/** number | null -> bare numeric | NULL */
function sqlNullableNum(v: number | null | undefined): string {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v !== 'number' || !Number.isFinite(v)) {
    throw new Error(`Non-finite numeric value: ${String(v)}`)
  }
  return String(v)
}

/**
 * Build a full seed file: DELETE preamble + chunked INSERT statements.
 * rowsPerInsert = floor(100 / numCols) per D1 placeholder/value limits.
 */
function buildSeedSql(opts: {
  table: string
  columns: string[]
  rows: string[][] // each cell already SQL-rendered
}): string {
  const { table, columns, rows } = opts
  const numCols = columns.length
  const rowsPerInsert = Math.floor(100 / numCols)
  if (rowsPerInsert < 1) throw new Error(`Too many columns for ${table}: ${numCols}`)

  // Validate every row has the right arity.
  for (const r of rows) {
    if (r.length !== numCols) {
      throw new Error(`Arity mismatch in ${table}: expected ${numCols}, got ${r.length}`)
    }
  }

  const colList = columns.join(', ')
  const lines: string[] = []
  lines.push(`-- AUTO-GENERATED by db/scripts/generate-seed.ts — DO NOT EDIT BY HAND.`)
  lines.push(`-- Reference seed for ${table} (${rows.length} rows, ${numCols} cols, ${rowsPerInsert} rows/insert).`)
  lines.push(`-- Idempotent: DELETE preamble fully reloads the reference table.`)
  lines.push(`DELETE FROM ${table};`)
  lines.push('')

  for (let i = 0; i < rows.length; i += rowsPerInsert) {
    const chunk = rows.slice(i, i + rowsPerInsert)
    const valueLines = chunk.map((r) => `  (${r.join(', ')})`)
    lines.push(`INSERT INTO ${table} (${colList}) VALUES`)
    lines.push(valueLines.join(',\n') + ';')
    lines.push('')
  }
  return lines.join('\n').replace(/\n+$/, '\n')
}

function loadJson<T>(path: string): T {
  return JSON.parse(readFileSync(path, 'utf8')) as T
}

// ---------------------------------------------------------------------------
// Source types
// ---------------------------------------------------------------------------
interface AircraftSrc {
  icao: string
  iata: string | null
  manufacturer: string
  model: string
  name: string
  type: string
  engineType: string
  engineCount: number
  capacity: number | null // present in JSON, OMITTED from D1 schema
}
interface AirportSrc {
  iata: string
  icao: string | null
  name: string
  city: string
  country: string
  countryCode: string
  latitude: number | null
  longitude: number | null
  timezone: string // present in JSON, OMITTED from D1 schema
}
interface BadgeSrc {
  id: number
  code: string
  name: string
  description: string | null
  category: string | null
  tier: string | null
  icon: string | null
  points: number | null
  criteria: unknown // object in snapshot -> JSON string in D1
}
interface WordSrc {
  word: string
}

interface AirportSupplement {
  sourceId: number
  iata: string
  icao: string
  name: string
  city: string
  countryCode: string
  latitude: number
  longitude: number
}

/** Explicitly additive seed for the eight public-domain source rows only. */
function genAirportSupplement(): void {
  const supplement = loadJson<{
    source: { url: string; sha256: string; license: string; attribution: string }
    airports: AirportSupplement[]
  }>(join(REPO, 'db', 'reference-supplements.json'))
  const countries = loadJson<Record<string, { name: string }>>(join(DATA, 'countries.json'))
  const base = loadJson<AirportSrc[]>(join(DATA, 'airports.json'))
  const baseCodes = new Set(base.map((a) => a.iata))
  const expected = ['ARK', 'BAX', 'KBV', 'MCX', 'MRV', 'NAL', 'VOG', 'ZIA']
  const actual = supplement.airports.map((a) => a.iata).sort()
  if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error('Unexpected supplemental airport code set')
  if (!/^[a-f0-9]{64}$/.test(supplement.source.sha256) || supplement.source.license !== 'Public Domain') {
    throw new Error('Supplement provenance is incomplete')
  }
  const columns = ['iata', 'icao', 'name', 'city', 'country', 'country_code', 'latitude', 'longitude']
  const lines = [
    '-- AUTO-GENERATED by db/scripts/generate-seed.ts --supplement-only.',
    `-- Source: ${supplement.source.url}`,
    `-- SHA-256: ${supplement.source.sha256}; license: ${supplement.source.license}; ${supplement.source.attribution}`,
    '-- Existing matching rows are no-ops; a divergent existing IATA raises a primary-key conflict.',
  ]
  for (const airport of supplement.airports) {
    if (baseCodes.has(airport.iata)) throw new Error(`Supplement duplicates base airport ${airport.iata}`)
    const country = countries[airport.countryCode]?.name
    if (!country) throw new Error(`Unknown supplement country code ${airport.countryCode}`)
    const values = [
      sqlStr(airport.iata), sqlStr(airport.icao), sqlStr(airport.name), sqlStr(airport.city),
      sqlStr(country), sqlStr(airport.countryCode), sqlNullableNum(airport.latitude),
      sqlNullableNum(airport.longitude),
    ]
    const equality = columns.map((col, i) => `${col} IS ${values[i]}`).join(' AND ')
    lines.push(`INSERT INTO airports_reference (${columns.join(', ')}) SELECT ${values.join(', ')} WHERE NOT EXISTS (SELECT 1 FROM airports_reference WHERE ${equality});`)
  }
  writeFileSync(join(OUT, 'airports_reference_supplement.sql'), lines.join('\n') + '\n')
}

// ---------------------------------------------------------------------------
// Generators
// ---------------------------------------------------------------------------
const results: Record<string, number> = {}
let realAirportCount = 0
let aircraftRawCount = 0
let droppedE135 = false

function genAircraft(): AircraftSrc[] {
  const raw = loadJson<AircraftSrc[]>(join(DATA, 'aircraft.json'))
  aircraftRawCount = raw.length

  // Dedup on icao: keep FIRST occurrence, drop the SECOND (E135 -> drop RJ140).
  const seen = new Set<string>()
  const deduped: AircraftSrc[] = []
  for (const a of raw) {
    if (seen.has(a.icao)) {
      if (a.icao === 'E135') droppedE135 = true
      continue
    }
    seen.add(a.icao)
    deduped.push(a)
  }
  if (deduped.length !== 214) {
    throw new Error(`ASSERT FAIL: expected 214 aircraft after dedup, got ${deduped.length}`)
  }

  // Deterministic sort by PK (icao).
  const sorted = [...deduped].sort((x, y) => (x.icao < y.icao ? -1 : x.icao > y.icao ? 1 : 0))

  // Columns EXACTLY per 0001_init.sql aircraft_reference (capacity OMITTED).
  const columns = ['icao', 'iata', 'name', 'manufacturer', 'model', 'type', 'engine_type', 'engine_count']
  const rows = sorted.map((a) => [
    sqlStr(a.icao),
    sqlNullableStr(a.iata),
    sqlStr(a.name),
    sqlStr(a.manufacturer),
    sqlStr(a.model),
    sqlStr(a.type),
    sqlStr(a.engineType),
    sqlNullableNum(a.engineCount),
  ])
  const sql = buildSeedSql({ table: 'aircraft_reference', columns, rows })
  writeFileSync(join(OUT, 'aircraft_reference.sql'), sql)
  results['aircraft_reference.sql'] = rows.length
  return deduped
}

function genAirports(): void {
  const raw = loadJson<AirportSrc[]>(join(DATA, 'airports.json'))
  realAirportCount = raw.length

  // Assert against the REAL count reported from packages/data.
  if (raw.length !== realAirportCount) {
    throw new Error('unreachable')
  }
  // Dedup defensively on iata PK (expect 0 dups -> count unchanged).
  const seen = new Set<string>()
  const deduped: AirportSrc[] = []
  for (const a of raw) {
    if (seen.has(a.iata)) continue
    seen.add(a.iata)
    deduped.push(a)
  }
  if (deduped.length !== raw.length) {
    throw new Error(`ASSERT FAIL: unexpected iata dups; raw=${raw.length} deduped=${deduped.length}`)
  }

  const sorted = [...deduped].sort((x, y) => (x.iata < y.iata ? -1 : x.iata > y.iata ? 1 : 0))

  // Columns EXACTLY per 0001_init.sql airports_reference (timezone OMITTED).
  const columns = ['iata', 'icao', 'name', 'city', 'country', 'country_code', 'latitude', 'longitude']
  const rows = sorted.map((a) => [
    sqlStr(a.iata),
    sqlNullableStr(a.icao),
    sqlStr(a.name),
    sqlStr(a.city),
    sqlStr(a.country),
    sqlStr(a.countryCode),
    sqlNullableNum(a.latitude),
    sqlNullableNum(a.longitude),
  ])
  const sql = buildSeedSql({ table: 'airports_reference', columns, rows })
  writeFileSync(join(OUT, 'airports_reference.sql'), sql)
  results['airports_reference.sql'] = rows.length
}

function genBadges(): void {
  const raw = loadJson<BadgeSrc[]>(join(SNAP, 'badge_definitions.json'))
  if (raw.length !== 60) {
    throw new Error(`ASSERT FAIL: expected 60 badge_definitions, got ${raw.length}`)
  }
  const maxId = Math.max(...raw.map((b) => b.id))
  if (maxId !== 63) {
    throw new Error(`ASSERT FAIL: expected max badge id 63, got ${maxId}`)
  }

  // Preserve explicit ids (incl. gaps) — deterministic sort by id.
  const sorted = [...raw].sort((a, b) => a.id - b.id)

  // Columns EXACTLY per 0001_init.sql badge_definitions.
  const columns = ['id', 'code', 'name', 'description', 'category', 'tier', 'icon', 'points', 'criteria']
  const rows = sorted.map((b) => {
    // criteria: object/dict in snapshot -> compact JSON string in TEXT column.
    const criteriaCell =
      b.criteria === null || b.criteria === undefined ? 'NULL' : sqlStr(JSON.stringify(b.criteria))
    return [
      sqlNullableNum(b.id),
      sqlStr(b.code),
      sqlStr(b.name),
      sqlNullableStr(b.description),
      sqlNullableStr(b.category),
      sqlNullableStr(b.tier),
      sqlNullableStr(b.icon),
      sqlNullableNum(b.points),
      criteriaCell,
    ]
  })
  const sql = buildSeedSql({ table: 'badge_definitions', columns, rows })
  writeFileSync(join(OUT, 'badge_definitions.sql'), sql)
  results['badge_definitions.sql'] = rows.length
}

function genWords(file: string, table: string, outName: string): void {
  const raw = loadJson<WordSrc[]>(join(SNAP, file))
  if (raw.length !== 50) {
    throw new Error(`ASSERT FAIL: expected 50 rows in ${file}, got ${raw.length}`)
  }
  const sorted = [...raw].sort((a, b) => (a.word < b.word ? -1 : a.word > b.word ? 1 : 0))
  const columns = ['word']
  const rows = sorted.map((w) => [sqlStr(w.word)])
  const sql = buildSeedSql({ table, columns, rows })
  writeFileSync(join(OUT, outName), sql)
  results[outName] = rows.length
}

// ---------------------------------------------------------------------------
// Validation — diff generated counts/samples vs source of truth
// ---------------------------------------------------------------------------
function validate(dedupedAircraft: AircraftSrc[]): string[] {
  const log: string[] = []

  // Aircraft: re-read source, recompute expected, sample-diff 3 PKs from SQL.
  const srcRaw = loadJson<AircraftSrc[]>(join(DATA, 'aircraft.json'))
  const expectedAircraft = new Map<string, AircraftSrc>()
  for (const a of srcRaw) if (!expectedAircraft.has(a.icao)) expectedAircraft.set(a.icao, a)
  if (expectedAircraft.size !== results['aircraft_reference.sql']) {
    throw new Error(
      `VALIDATE FAIL aircraft: dedup map ${expectedAircraft.size} != generated ${results['aircraft_reference.sql']}`,
    )
  }
  const acSql = readFileSync(join(OUT, 'aircraft_reference.sql'), 'utf8')
  for (const icao of ['A124', 'B738', 'E135']) {
    const a = expectedAircraft.get(icao)!
    // E135 in SQL must be the FIRST (RJ135), not the dropped RJ140.
    if (!acSql.includes(sqlStr(a.name))) {
      throw new Error(`VALIDATE FAIL aircraft sample: ${icao} (${a.name}) not in SQL`)
    }
  }
  // Confirm dropped E135 row (RJ140) is NOT present.
  const rj140Present = acSql.includes(sqlStr('Embraer RJ140'))
  if (rj140Present) throw new Error('VALIDATE FAIL: dropped E135 RJ140 present in aircraft SQL')
  log.push(`aircraft: src=${srcRaw.length} deduped=${expectedAircraft.size} RJ140-dropped=${!rj140Present}`)

  // Airports sample-diff.
  const apRaw = loadJson<AirportSrc[]>(join(DATA, 'airports.json'))
  const apSql = readFileSync(join(OUT, 'airports_reference.sql'), 'utf8')
  for (const a of [apRaw[0], apRaw[Math.floor(apRaw.length / 2)], apRaw[apRaw.length - 1]]) {
    if (!apSql.includes(sqlStr(a.iata)) || !apSql.includes(sqlStr(a.name))) {
      throw new Error(`VALIDATE FAIL airport sample: ${a.iata} not in SQL`)
    }
  }
  log.push(`airports: src=${apRaw.length} generated=${results['airports_reference.sql']} sample-diff=PASS`)

  // Flights cross-check (scoped requirement): confirm NO flight references the
  // dropped E135 row. Both source E135 rows share icao 'E135' and the kept row
  // is RJ135, so it suffices to confirm no flight uses 'E135' at all -> the
  // dedup choice (drop RJ140) cannot orphan any flight. This is a HARD assert.
  const flights = loadJson<Array<{ aircraft_icao: string | null }>>(join(SNAP, 'flights.json'))
  const flightIcaos = new Set(flights.map((f) => f.aircraft_icao))
  const e135Refs = flights.filter((f) => f.aircraft_icao === 'E135').length
  if (e135Refs !== 0) {
    throw new Error(`VALIDATE FAIL: ${e135Refs} flight(s) reference dropped E135 row`)
  }

  // Broader FK survey (informational, NOT a seed failure): report any flight
  // aircraft_icao absent from the reference set. These are pre-existing live
  // data-quality issues to be handled by the flights-import agent, not by the
  // reference seed (the seed must mirror packages/data row-for-row).
  const dedupSet = new Set(dedupedAircraft.map((a) => a.icao))
  const orphans: string[] = []
  for (const icao of flightIcaos) {
    if (icao !== null && !dedupSet.has(icao)) orphans.push(icao)
  }
  log.push(
    `flights: ${flights.length} rows, ${flightIcaos.size} distinct aircraft_icao, E135-refs=${e135Refs} (dropped row unreferenced=PASS)`,
  )
  log.push(
    `flights FK survey (informational): ${orphans.length} non-reference aircraft_icao -> [${orphans.join(', ')}]`,
  )

  return log
}

