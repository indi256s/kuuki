import { readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../packages/data/src/airports.json', import.meta.url)
const airports = JSON.parse(readFileSync(source, 'utf8'))
const labels = airports.map(({ iata, name, city }) => ({ iata, name, city }))
const details = airports.map(({ iata: _iata, name: _name, city: _city, ...detail }) => detail)
const rows = (values) => values.map((value) => `  ${JSON.stringify(value)},`).join('\n')
const header = '// Generated by pnpm generate:airport-catalog from airports.json; do not edit.\n'
const outputs = {
  'airport-labels.generated.ts': `${header}\
import type { Airport } from '@kuuki/shared/types'

export type AirportLabel = Pick<Airport, 'iata' | 'name' | 'city'>

export const airportLabels: AirportLabel[] = [
${rows(labels)}
]
`,
  'airport-details.generated.ts': `${header}\
import type { Airport } from '@kuuki/shared/types'
import type { AirportLabel } from './airport-labels.generated'

export const airportDetails: Omit<Airport, keyof AirportLabel>[] = [
${rows(details)}
]
`,
}

for (const [filename, output] of Object.entries(outputs)) {
  const target = new URL(`../packages/data/src/${filename}`, import.meta.url)
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== output) {
      console.error(`${filename} is stale. Run pnpm generate:airport-catalog.`)
      process.exitCode = 1
    }
  } else {
    writeFileSync(target, output)
  }
}
