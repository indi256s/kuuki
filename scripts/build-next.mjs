import { execFileSync } from 'node:child_process'
import { cpSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { compileActivationAsset } from './activation-asset.mjs'

const root = resolve(import.meta.dirname, '..')
const apiDir = join(root, 'functions/api')
const generated = join(root, 'apps/next/api-routes.generated.ts')
const routes = []

function scan(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) {
      scan(path)
      continue
    }
    if (!entry.name.endsWith('.ts') || entry.name.startsWith('_')) continue
    const text = readFileSync(path, 'utf8')
    const exports = [
      ...text.matchAll(/export const onRequest(Get|Post|Put|Patch|Delete|Head|Options)?\s*:/g),
    ]
    if (exports.length === 0) continue
    const rel = relative(apiDir, path).replaceAll('\\', '/')
    if (rel === 'auth/[[path]].ts') continue // Deliberately enumerate Better Auth's supported URLs.
    const route = '/api/' + rel.replace(/(?:\/index)?\.ts$/, '').replace(/\[([^\]]+)\]/g, ':$1')
    const methods = exports.flatMap((match) => (match[1] ? [match[1].toUpperCase()] : []))
    if (methods.length === 0) throw new Error(`Unbounded API handler: ${rel}`)
    routes.push({ route, methods })
  }
}
scan(apiDir)
routes.push(
  { route: '/api/auth/sign-in/email', methods: ['POST'] },
  { route: '/api/auth/sign-up/email', methods: ['POST'] },
  { route: '/api/auth/sign-out', methods: ['POST'] },
  { route: '/api/auth/get-session', methods: ['GET'] },
)
routes.sort((a, b) => a.route.localeCompare(b.route))
writeFileSync(
  generated,
  `// Generated by scripts/build-next.mjs from Pages Functions exports.\nexport const apiRoutes = ${JSON.stringify(routes, null, 2)} as const\n`,
)
if (process.argv.includes('--inventory-only')) process.exit(0)

execFileSync('pnpm', ['build:api'], { cwd: root, stdio: 'inherit' })
execFileSync('pnpm', ['--filter', '@kuuki/next', 'exec', 'opennextjs-cloudflare', 'build'], {
  cwd: root,
  stdio: 'inherit',
})

const assets = join(root, 'apps/next/.open-next/assets')
writeFileSync(
  join(assets, 'activate.html'),
  compileActivationAsset(
    readFileSync(join(root, 'apps/next/activation/activate.html'), 'utf8'),
    readFileSync(join(root, 'apps/next/src/app/styles.css'), 'utf8'),
  ),
)
cpSync(join(root, 'apps/next/activation/activate.js'), join(assets, 'activate.js'))
cpSync(join(root, 'apps/next/transition/sw.js'), join(assets, 'sw.js'))
cpSync(join(root, 'apps/next/transition/registerSW.js'), join(assets, 'registerSW.js'))

const worker = join(root, 'apps/next/.open-next/worker.js')
let assetCount = 0
let assetBytes = 0
function measure(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) measure(path)
    else {
      assetCount++
      assetBytes += statSync(path).size
    }
  }
}
measure(assets)
console.log(
  JSON.stringify({
    node: process.version,
    openNextEntryBytes: statSync(worker).size,
    assetCount,
    assetBytes,
    apiRoutes: routes.length,
  }),
)
