// ---------- CSS: the kit's rules scoped under .wp-bench, keeping only those the figure can match ----------
const SCOPE = '.wp-bench'
function rulesOf(css) {
  const rules = []
  let depth = 0
  let start = 0
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) {
      rules.push(css.slice(start, i + 1).trim())
      start = i + 1
    }
  }
  return rules.filter(Boolean)
}
const scoped = (selector) =>
  selector
    .split(',')
    .map((part) => `${SCOPE} ${part.trim()}`)
    .join(',')
// Rules for parts the figure never has: materials, plates, legends and keys, wires, tubes, flowing and pulsing lines
// (with their keyframes), dashes and the red, green and blue tones.
const UNUSED =
  /data-mat|iso-(plate|legend|key|swatch|wire|figure|flow|pulse|face-text)|\.tb\b|tb-|data-(flow|pulse|dashed)|"(red|green|blue)"|@keyframes/
function scope(css) {
  return rulesOf(css)
    .flatMap((rule) => {
      const open = rule.indexOf('{')
      const head = rule.slice(0, open).trim()
      const inner = rule.slice(open + 1, -1)
      if (UNUSED.test(head)) return []
      if (head.startsWith('@media')) {
        const kept = scope(inner)
        return kept ? [`${head}{${kept}}`] : []
      }
      // The kit's palettes: bench.css maps every --anatomy-* role onto Kuuki's tokens.
      if (/^\.iso(\[data-theme="(dark|light)"\])?$/.test(head)) return []
      return [`${scoped(head)}{${inner}}`]
    })
    .join('\n')
}
