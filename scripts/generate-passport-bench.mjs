function bench() {
  const out = [`<path class="iso-halo" d="${k.haloOf(PLATE, -PLATE_H - FOOT_H, PLATE_H, P)}"/>`]
  for (const [x, y] of byDepth(k.corners(PLATE, 20))) {
    out.push(S(k.cylinder(x, y, 6.5, -PLATE_H - FOOT_H, 1.4, P, 28), { tone: 'lo' }))
    out.push(S(k.cylinder(x, y, 5, -PLATE_H - FOOT_H + 1.4, FOOT_H - 1.4, P, 28), { tone: 'mid' }))
  }
  out.push(
    S(k.slabOf(PLATE, -PLATE_H, PLATE_H, P, 8, 1.4), {
      tone: 'mid',
      inner: L(k.sideSeam(PLATE, -3, P, 8), { tone: 'faint' }),
    }),
  )
  out.push(L(k.planOutline(k.insetPlan(PLATE, 4.5), 0, P), { tone: 'lo' }))
  const screws = k.corners(PLATE, 9)
  out.push(L(screws.map(([x, y]) => k.ring(x, y, 2, 0, P, 16)).join(''), { tone: 'lo' }))
  out.push(
    Dt(
      screws.map(([x, y]) => at([x, y, 0])),
      { size: 0.5 },
    ),
  )
  // Label plate at the back left: three rule lines stand for its printing.
  const label = { x: -94, y: -21, w: 44, d: 11, r: 1.2 }
  out.push(S(k.slabOf(label, 0, 0.8, P, 4), { tone: 'lo', crease: 'none' }))
  out.push(L(k.planOutline(k.insetPlan(label, 1.4), 0.8, P, 3), { tone: 'faint' }))
  out.push(
    L(
      [
        [label.x + 5, label.x + 30, label.y + 3.8],
        [label.x + 5, label.x + 38, label.y + 5.8],
        [label.x + 5, label.x + 22, label.y + 7.6],
      ]
        .map(([a, b, y]) => k.lineOnTop([a, y], [b, y], 0.8, P))
        .join(''),
      { tone: 'lo', free: true },
    ),
  )
  out.push(
    Dt(
      [at([label.x + 2.2, label.y + 5.5, 0.8]), at([label.x + label.w - 2.2, label.y + 5.5, 0.8])],
      { size: 0.45 },
    ),
  )
  // Ruler strip along the front left edge, ticks rooted on its far edge.
  const strip = { x: -96, y: 134, w: 92, d: 7, r: 1 }
  out.push(S(k.slabOf(strip, 0, 0.6, P, 3), { tone: 'lo', crease: 'none' }))
  const ticks = k.topTicks(
    strip.x + 3,
    strip.x + strip.w - 3,
    3,
    5,
    strip.y + 0.6,
    0.6,
    [2, 3.6],
    P,
  )
  out.push(L(ticks.minor, { tone: 'lo' }), L(ticks.major, { tone: 'mid' }))
  out.push(
    Dt([at([strip.x + 1.5, strip.y + 5, 0.6]), at([strip.x + strip.w - 1.5, strip.y + 5, 0.6])], {
      size: 0.45,
    }),
  )
  return out.join('')
}

function rail(plan) {
  const out = []
  for (const x of [plan.x - 5, plan.x + plan.w]) {
    out.push(
      S(k.slabOf({ x, y: plan.y - 3, w: 5, d: 10, r: 1.2 }, 0, 7, P, 3, 0.4), { tone: 'mid' }),
    )
    out.push(Dt([at([x + 2.5, plan.y - 1, 7]), at([x + 2.5, plan.y + 5, 7])], { size: 0.45 }))
  }
  out.push(S(k.slabOf(plan, 0, RAIL_H, P, 3, 0.4), { tone: 'mid' }))
  out.push(
    L(k.lineOnTop([plan.x, plan.y + 2], [plan.x + plan.w, plan.y + 2], RAIL_H, P), {
      tone: 'faint',
    }),
  )
  out.push(
    Dt(
      [20, 60, 100, 150].map((x) => at([x, plan.y + 2, RAIL_H])),
      { size: 0.4 },
    ),
  )
  return out.join('')
}

