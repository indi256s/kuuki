// Generates the onboarding passport figure: an open passport on an issuing bench, with a stamping bridge that presses
// one stamp per country the import finds. Drawn with the anatomy skill's iso kit, pinned with the Concorde's
// (scripts/concorde/anatomy.lock.json; setup in scripts/concorde/README.md). The approved prototype was
// .scratch/onboarding-passport-figure/build.mjs; this is its drawing, unchanged.
//
//   pnpm generate:passport-bench
//
// Outputs, all in apps/next/src/client/welcome/passport/:
//   bench.generated.ts       the static SVG (bench, rails, passport, bridge) with empty live slots, and its projection
//   bench.generated.css      the kit's figure CSS, scoped under .wp-bench (colours come from bench.css)
//   iso-kit.generated.js     the kit's iso module (MIT; the licence is in its header), with iso-kit.generated.d.ts;
//                            bench-geom.ts and bench-live.ts redraw the leaf and the plungers with it at runtime
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const pin = JSON.parse(
  readFileSync(new URL('./concorde/anatomy.lock.json', import.meta.url), 'utf8'),
)
const KIT = resolve(process.env.ANATOMY_KIT ?? '.scratch/concorde/anatomy/kit')
const OUT = resolve('apps/next/src/client/welcome/passport')
for (const file of ['iso-kit.mjs', 'iso.css', '../LICENSE']) {
  let actual
  try {
    actual = createHash('sha256')
      .update(readFileSync(join(KIT, file)))
      .digest('hex')
  } catch {
    throw new Error(`Missing anatomy kit file ${file}. See scripts/concorde/README.md for setup.`)
  }
  if (actual !== pin.sha256[file])
    throw new Error(
      `Anatomy kit ${file} differs from pinned commit ${pin.commit}. See scripts/concorde/README.md.`,
    )
}

