function inkPad() {
  const out = [
    `<path class="iso-halo" d="${k.haloOf(PAD_TIN, 0, 3, P)}" style="filter:blur(5px)"/>`,
  ]
  out.push(
    S(k.slabOf(PAD_TIN, 0, 3.2, P, 6, 0.6), {
      tone: 'mid',
      inner: L(k.sideSeam(PAD_TIN, 1.4, P, 6), { tone: 'faint' }),
    }),
  )
  const top = 3.8
  const felt = k.insetPlan(PAD, 1.6)
  // Inked felt: a nap of fine lines along the pad, each ending on the inset rim, fading toward both sides; and the marks
  // the parked dies have left (closed outlines, so they have no ends).
  const nap = []
  for (let x = felt.x + 2, i = 0; x < felt.x + felt.w - 1; x += 2.2, i++) {
    const t = (x - felt.x) / felt.w
    nap.push({
      d: k.lineOnTop([x, felt.y], [x, felt.y + felt.d], top, P),
      alpha: 0.25 + 0.75 * Math.sin(Math.PI * t) * (i % 2 ? 0.7 : 1),
    })
  }
  const marks =
    PP.ROWS.map((y) => k.ring(PP.PARK, y, PP.STAMP_R - 0.8, top, P, 48)).join('') +
    k.planOutline(
      {
        x: PP.PARK - PP.ENTRY.w / 2 + 0.6,
        y: PP.ENTRY.y - PP.ENTRY.h / 2 + 0.6,
        w: PP.ENTRY.w - 1.2,
        d: PP.ENTRY.h - 1.2,
        r: 1.4,
      },
      top,
      P,
      3,
    )
  out.push(
    g(
      'pp-ink',
      S(k.slabOf(PAD, 3.2, 0.6, P, 4), { tone: 'lo', crease: 'none' }) +
        `<g class="pp-ink-tex">${k.fadedSvg(
          nap.map(({ d, alpha }) => [d, alpha]),
          { tone: 'faint' },
        )}</g>` +
        `<g class="pp-ink-mark">${L(marks, { tone: 'faint' })}</g>`,
    ),
  )
  out.push(L(k.planOutline(felt, top, P, 4), { tone: 'faint', className: 'pp-ink-rim' }))
  out.push(
    Dt(
      [
        at([PAD_TIN.x + 1.3, PAD_TIN.y + 4, 3.2]),
        at([PAD_TIN.x + PAD_TIN.w - 1.3, PAD_TIN.y + PAD_TIN.d - 4, 3.2]),
      ],
      {
        size: 0.45,
      },
    ),
  )
  return out.join('')
}

// ---------- Printed art (page-plane coordinates) ----------
const WAVES = Array.from({ length: 5 }, (_, i) => ({
  amp: 2.6 + i * 1.5,
  phase: i * 3.1,
  opacity: 0.95 - i * 0.14,
}))
function guilloche(v0, v1) {
  const mid = (v0 + v1) / 2
  const out = []
  for (const { amp, phase, opacity } of WAVES) {
    for (const sign of [-1, 1]) {
      const pts = []
      for (let u = 0; u <= W + 1e-6; u += 1)
        pts.push([u, mid + sign * amp * Math.sin(((u + phase) / 14) * Math.PI)])
      out.push(
        `<g opacity="${opacity.toFixed(2)}">${L(k.pathOf(pts), { tone: 'faint', className: 'pp-guilloche' })}</g>`,
      )
    }
  }
  return out.join('')
}
