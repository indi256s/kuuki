const Dt = (points, style) => k.dotsSvg(points, style)
const byDepth = (pts) =>
  [...pts].sort((a, b) => k.depthOf([a[0], a[1], 0], P) - k.depthOf([b[0], b[1], 0], P))
const g = (cls, inner, extra = '') => `<g class="${cls}"${extra}>${inner}</g>`

