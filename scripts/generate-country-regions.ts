/**
 * Generates functions/api/_lib/countryRegions.generated.ts from the catalog (`packages/data/src/countries.json`,
 * the `continent` field). `functions/` cannot import `@kuuki/data`, so the six-region map is checked in and a
 * parity test (functions/test/regions.test.ts) fails when the catalog and the map diverge.
 * Run: pnpm generate:regions
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const OUTPUT = join(ROOT, 'functions', 'api', '_lib', 'countryRegions.generated.ts')

export function render(catalog: Record<string, { continent: string }>): string {
  const codes = Object.keys(catalog).sort()
  const regions = [...new Set(codes.map(code => catalog[code].continent))].sort()
  const totals = Object.fromEntries(regions.map(region => [region, codes.filter(code => catalog[code].continent === region).length]))
  return `// GENERATED by scripts/generate-country-regions.ts from packages/data/src/countries.json. Do not edit by hand.
// Run \`pnpm generate:regions\` after a catalog change; functions/test/regions.test.ts checks parity.

export const REGION_IDS = ${JSON.stringify(regions)} as const
export type RegionId = (typeof REGION_IDS)[number]

/** Catalog countries per region. */
export const REGION_TOTALS: Record<RegionId, number> = ${JSON.stringify(totals)}

/** Catalog country code to collection region. */
export const COUNTRY_REGION: Readonly<Record<string, RegionId>> = {
${codes.map(code => `  ${code}: '${catalog[code].continent}',`).join('\n')}
}
`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const catalog = JSON.parse(readFileSync(join(ROOT, 'packages', 'data', 'src', 'countries.json'), 'utf8'))
  writeFileSync(OUTPUT, render(catalog))
  console.log(`wrote ${OUTPUT}`)
}
