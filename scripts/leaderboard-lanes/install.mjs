// Installs the generated lane vehicles into the app. Inputs are the committed generator outputs, so this step needs
// no anatomy kit: run fleet.mjs / build.mjs first only when the drawings change.
//
//   node scripts/leaderboard-lanes/install.mjs
//
// Writes apps/next/src/client/leaderboard/lanes/:
//   art/<KEY>.svg            one <symbol id="lane-KEY"> per airliner type, the locomotive (rail) and the 993 (road).
//                            The page imports them as static media, so each gets a content-hashed, cached URL and a
//                            board fetches only the files its <use> elements name.
//   vehicles.generated.css   the host rules (colour roles, livery, level of detail) that reach into <use> clones.
//   lanes.generated.ts       the URLs plus the geometry a lane needs: viewBox, nose and ground line per family.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const FLEET = '.scratch/leaderboard-lanes/fleet'
const GATE = '.scratch/leaderboard-lanes/gate'
const OUT = 'apps/next/src/client/leaderboard/lanes'

const fleetMeta = JSON.parse(readFileSync(join(FLEET, 'meta.json'), 'utf8'))
const gateMeta = JSON.parse(readFileSync(join(GATE, 'meta.json'), 'utf8'))
const types = readdirSync(FLEET)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -4))
  .sort()

// The root carries the symbol's size: Next reads image dimensions from every imported SVG.
const sized = (symbol) => {
  const [, , w, h] = symbol
    .match(/viewBox="([^"]+)"/)[1]
    .split(' ')
    .map(Number)
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${Math.ceil(w)}" height="${Math.ceil(h)}">${symbol}</svg>`
}
const symbolOf = (svg, key) => {
  const symbol = svg.match(new RegExp(`<symbol id="lane-${key}"[\\s\\S]*?</symbol>`))?.[0]
  if (!symbol) throw new Error(`lane-${key} symbol not found`)
  return symbol
}

rmSync(join(OUT, 'art'), { recursive: true, force: true })
mkdirSync(join(OUT, 'art'), { recursive: true })
for (const key of types)
  writeFileSync(
    join(OUT, 'art', `${key}.svg`),
    sized(symbolOf(readFileSync(join(FLEET, `${key}.svg`), 'utf8'), key)),
  )

// The gate sprite holds the air, rail and road symbols; the ground vehicles get one file each, like the fleet.
const sprite = readFileSync(join(GATE, 'sprite.svg'), 'utf8')
for (const key of ['rail', 'road'])
  writeFileSync(join(OUT, 'art', `${key}.svg`), sized(symbolOf(sprite, key)))

// Host rules only: the art rules travel inside each symbol, where document CSS cannot reach.
const css = readFileSync(join(FLEET, 'vehicles.css'), 'utf8')
const host = css.slice(css.indexOf('\n') + 1, css.indexOf('.lane-art path'))
if (host.length < 200) throw new Error('vehicles.css host rules not found')
writeFileSync(
  join(OUT, 'vehicles.generated.css'),
  `/* Generated by scripts/leaderboard-lanes/install.mjs from ${FLEET}/vehicles.css. Do not edit. */\n${host.trimEnd()}\n`,
)

const geometry = (meta) => {
  const [x, y, w, h] = meta.viewBox
  return {
    viewBox: [x, y, w, h].map((n) => Math.round(n * 100) / 100),
    // Where the nose meets the ground, as fractions of the viewBox, and the drawn length of a 100-unit vehicle.
    nose: Math.round(((meta.nose[0] - x) / w) * 10000) / 10000,
    ground: Math.round(((meta.nose[1] - y) / h) * 10000) / 10000,
    unit: Math.round((meta.nose[0] - meta.tail[0]) * 100) / 100,
  }
}
const id = (key) => `art_${key}`
writeFileSync(
  join(OUT, 'lanes.generated.ts'),
  `// Generated by scripts/leaderboard-lanes/install.mjs. Do not edit.
${[...types, 'rail', 'road'].map((key) => `import ${id(key)} from './art/${key}.svg'`).join('\n')}

export const LANE_TYPES = ${JSON.stringify(types)} as const
export type LaneVehicleKey = (typeof LANE_TYPES)[number] | 'rail' | 'road'

/** Static imports resolve to a URL string under Vite and to image data under Next. */
type Asset = string | { src: string }
export const laneArt: Record<LaneVehicleKey, Asset> = {
${[...types, 'rail', 'road'].map((key) => `  ${key}: ${id(key)},`).join('\n')}
}

export const laneGeometry = {
  air: ${JSON.stringify(geometry(fleetMeta))},
  ground: ${JSON.stringify(geometry(gateMeta))},
} as const
`,
)
console.log(`installed ${types.length} airliners + rail + road into ${OUT}`)
