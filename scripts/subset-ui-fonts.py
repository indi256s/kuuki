#!/usr/bin/env python3
"""Generate UI font shards and their CSS from the original, unchanged WOFF2 files.

Run from the workspace root: python3 scripts/subset-ui-fonts.py
Verify regeneration without writing: python3 scripts/subset-ui-fonts.py --check
Requires Python fontTools with WOFF2 support: pip install 'fonttools[woff]'
Generated with fontTools 4.63.0 and Brotli 1.2.1; use these versions for identical
compressed bytes. Neither package is an application runtime dependency.
Coverage comes from each original cmap. Shards overlap only on combining marks
to preserve decomposed text across scripts; CSS ranges are generated from them.
"""

import argparse
from io import BytesIO
from pathlib import Path
import re
import textwrap
import unicodedata

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'apps/next/public/fonts'
STYLES = ROOT / 'apps/next/src/app/styles.css'
FACES = (
    ('Commissioner-Regular', 'Commissioner', '400'),
    ('Commissioner-Medium', 'Commissioner', '500'),
    ('Commissioner-SemiBold', 'Commissioner', '600'),
    ('Commissioner-Bold', 'Commissioner', '700'),
    ('PaperMono', 'Paper Mono', '100 800'),
)
MARKER = '/* Generated by python3 scripts/subset-ui-fonts.py; preserve original fonts. */'


def unicode_cmap(font: TTFont) -> set[int]:
    return {
        point
        for table in font['cmap'].tables
        if table.isUnicode()
        for point in table.cmap
    }


def layout_features(font: TTFont) -> set[tuple[str, str]]:
    return {
        (table, record.FeatureTag)
        for table in ('GSUB', 'GPOS')
        if table in font
        for record in font[table].table.FeatureList.FeatureRecord
    }


def is_latin_common(point: int) -> bool:
    # A partition policy, not a coverage inventory: intersect it with each cmap.
    # Include extended Latin, combining marks, punctuation and currency symbols.
    # Private-use symbols stay with Latin so Paper Mono's logo + "Paper" calt
    # context is not divided between font faces.
    return (
        point <= 0x024F
        or 0x0300 <= point <= 0x036F
        or 0x1E00 <= point <= 0x1EFF
        or 0x2000 <= point <= 0x206F
        or 0x20A0 <= point <= 0x20CF
        or 0xE000 <= point <= 0xF8FF
        or point in (0x2113, 0x2212, 0xFEFF, 0xFFFD)
    )


def unicode_ranges(points: set[int]) -> str:
    spans: list[str] = []
    ordered = sorted(points)
    start = end = ordered[0]
    for point in ordered[1:] + [None]:
        if point == end + 1:
            end = point
            continue
        spans.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
        start = end = point
    return ', '.join(spans)


def make_subset(source: bytes, points: set[int]) -> bytes:
    font = TTFont(BytesIO(source), recalcTimestamp=False)
    options = subset.Options()
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    options.notdef_outline = True
    options.glyph_names = True
    options.passthrough_tables = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    output = BytesIO()
    font.save(output)
    return output.getvalue()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated files without writes')
    args = parser.parse_args()
    generated: dict[Path, bytes] = {}
    rules = [MARKER]
    for filename, family, weight in FACES:
        source = (FONTS / f'{filename}.woff2').read_bytes()
        source_font = TTFont(BytesIO(source))
        original = unicode_cmap(source_font)
        latin = {point for point in original if is_latin_common(point)}
        # Retain combining marks in both faces for decomposed Cyrillic/Greek
        # and Latin text. Latin comes last in CSS so shared marks alone do not
        # make an otherwise Latin run request the remaining shard.
        marks = {point for point in original if unicodedata.category(chr(point)).startswith('M')}
        partitions = {'remaining': (original - latin) | marks, 'latin': latin | marks}
        coverage: set[int] = set()
        features: set[tuple[str, str]] = set()
        sizes = {}
        for name, points in partitions.items():
            data = make_subset(source, points)
            if data != make_subset(source, points):
                raise ValueError(f'{filename}/{name}: nondeterministic regeneration')
            font = TTFont(BytesIO(data))
            actual = unicode_cmap(font)
            if actual != points or (coverage & actual) - marks:
                raise ValueError(f'{filename}/{name}: incorrect cmap partition')
            coverage |= actual
            features |= layout_features(font)
            for point, glyph in font.getBestCmap().items():
                original_glyph = source_font.getBestCmap()[point]
                if font['hmtx'][glyph] != source_font['hmtx'][original_glyph]:
                    raise ValueError(f'{filename}/{name}: changed advance at U+{point:X}')
            if 'fvar' in source_font and (
                font['fvar'].compile(font) != source_font['fvar'].compile(source_font)
            ):
                raise ValueError(f'{filename}/{name}: changed variation axes or instances')
            sizes[name] = len(data)
            asset = f'{filename}-{name}.woff2'
            generated[FONTS / asset] = data
            ranges = textwrap.fill(
                unicode_ranges(points) + ';',
                width=100,
                initial_indent='    ',
                subsequent_indent='    ',
                break_long_words=False,
                break_on_hyphens=False,
            )
            rules.append(
                '@font-face {\n'
                f'  font-family: {family};\n'
                f"  src: url('/fonts/{asset}') format('woff2');\n"
                '  font-style: normal;\n'
                f'  font-weight: {weight};\n'
                '  font-display: swap;\n'
                f'  unicode-range:\n{ranges}\n'
                '}'
            )
        if coverage != original:
            raise ValueError(f'{filename}: incomplete cmap coverage')
        if not layout_features(source_font) <= features:
            raise ValueError(f'{filename}: missing OpenType layout features')
        print(f'{filename}: original={len(source)} latin={sizes["latin"]} '
              f'remaining={sizes["remaining"]}; {len(original)} codepoints preserved')

    styles = STYLES.read_text()
    faces = list(re.finditer(r'@font-face\s*\{[^}]*\}', styles))
    if not faces or not re.fullmatch(
        r'(?:@font-face\s*\{[^}]*\}\s*)+',
        styles[faces[0].start():faces[-1].end()],
    ):
        raise ValueError('Expected one contiguous UI @font-face block')
    start = styles.index(MARKER) if MARKER in styles else faces[0].start()
    updated = styles[:start] + '\n'.join(rules) + styles[faces[-1].end():]
    generated[STYLES] = updated.encode()
    for path, data in generated.items():
        if path.exists() and path.read_bytes() == data:
            continue
        if args.check:
            raise ValueError(f'Outdated generated file: {path.relative_to(ROOT)}')
        path.write_bytes(data)
    print('Verified deterministic bytes, advances, layout features, variation axes and complete coverage; '
          'only combining marks overlap.')


if __name__ == '__main__':
    main()
