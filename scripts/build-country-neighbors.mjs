// Derives land neighbors from the pinned country geometry and writes packages/data/src/country-neighbors.ts.
//
//   node scripts/build-country-neighbors.mjs
//
// world-atlas is TopoJSON: neighboring countries share the same arcs, so after decoding they share identical
// consecutive vertices. Two countries are neighbors when at least one boundary edge (two consecutive vertices)
// is shared. A single shared point (a tripoint touch) is not enough. Only catalog codes are kept.
import { readFileSync, writeFileSync } from 'node:fs'

const geometryPath = 'apps/next/public/maps/countries-110m-2.0.2.geojson'
const outputPath = 'packages/data/src/country-neighbors.ts'
const catalog = JSON.parse(readFileSync('packages/data/src/countries.json', 'utf8'))
const { features } = JSON.parse(readFileSync(geometryPath, 'utf8'))

const edges = new Map()
for (const feature of features) {
  const polygons =
    feature.geometry.type === 'Polygon'
      ? [feature.geometry.coordinates]
      : feature.geometry.coordinates
  for (const ring of polygons.flat()) {
    for (let i = 1; i < ring.length; i++) {
      const a = ring[i - 1].join(','),
        b = ring[i].join(',')
      if (a === b) continue
      const key = a < b ? `${a}|${b}` : `${b}|${a}`
      if (!edges.has(key)) edges.set(key, new Set())
      edges.get(key).add(feature.id)
    }
  }
}
const neighbors = new Map()
for (const ids of edges.values()) {
  if (ids.size < 2) continue
  for (const a of ids)
    for (const b of ids) {
      if (a === b || !catalog[a] || !catalog[b]) continue
      if (!neighbors.has(a)) neighbors.set(a, new Set())
      neighbors.get(a).add(b)
    }
}
const lines = [...neighbors.keys()].sort().map(
  (code) =>
    `  ${code}: [${[...neighbors.get(code)]
      .sort()
      .map((n) => `'${n}'`)
      .join(', ')}],`,
)
writeFileSync(
  outputPath,
  `// Generated by scripts/build-country-neighbors.mjs. Do not edit by hand.
//
// Source: Natural Earth 1:110m Admin 0 countries (public domain, https://www.naturalearthdata.com/about/terms-of-use/),
// as packaged in world-atlas 2.0.2 (https://github.com/topojson/world-atlas/tree/v2.0.2, ISC) and pinned in
// ${geometryPath} (see docs/research/2026-10-04-map-implementation.md).
// Two catalog countries are neighbors when their low-detail outlines share a land boundary edge. A catalog code has
// no entry when the atlas has no outline for it (microstates, many small islands and territories, Kosovo) or when its
// outline shares no land boundary at this resolution (for example Australia, Iceland and Japan). Suggestions then fall
// back to recent countries, and search always covers the whole catalog. Used only for "add a country" suggestions,
// never for evidence.

export const COUNTRY_NEIGHBORS: Readonly<Record<string, readonly string[]>> = {
${lines.join('\n')}
}
`,
)
console.log(`${neighbors.size} countries with neighbors written to ${outputPath}`)
